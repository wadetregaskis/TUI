import collections
import json
import os
import re
import sys
import time
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import assigner  # noqa: E402
import checks  # noqa: E402
import indexstore  # noqa: E402
from model import Model  # noqa: E402
from rules import Rules  # noqa: E402

MAP = os.path.join(HERE, 'map.json')
RULES = os.path.join(HERE, 'rules.json')


# ── map.json ──────────────────────────────────────────────────────────────────────────────────────────────
def to_map(M, R, asg):
    """{file: module} for a file wholly in one module; {file: {label: module, ...}} naming every declaration of a
    split one."""
    files = {}
    by_file = collections.defaultdict(list)
    for n in M.nodes: by_file[M.file[n]].append(n)
    for f in M.files:
        ns = by_file.get(f)
        if not ns:
            files[f] = R.seed(f)[0]; continue
        mods = {asg[n] for n in ns}
        files[f] = mods.pop() if len(mods) == 1 else {M.short_label(n): asg[n] for n in ns}
    return files


def resolve(M, R, files):
    """The assignment map.json gives, and the declarations it does not name.

    Where map.json is silent the rules decide: a declaration rule, else for an extension in a default-module file
    the module of the type it extends, else the file's module (a split file's most common one). One exception: in a
    split file, a declaration it does not name beside exactly one entry no declaration claims, both of the same
    name (`View(ext)`), is that entry's declaration edited (a member added above its first one, or renamed), not a
    new one, and keeps the entry's module. Returns (assignment, unmapped declarations, how many kept an entry)."""
    asg, unmapped = {}, []
    for n in M.nodes:
        e = files.get(M.file[n])
        if isinstance(e, str):
            asg[n] = e; continue
        m = e.get(M.short_label(n)) if isinstance(e, dict) else None
        if m is None:
            unmapped.append(n)
            r = R.decl_rule(M.rule_labels(n))
            if r: m = r['module']
        asg[n] = m
    kept = 0
    by_file = collections.defaultdict(list)
    for n in unmapped: by_file[M.file[n]].append(n)
    for f, ns in by_file.items():
        e = files.get(f)
        if not isinstance(e, dict): continue
        claimed = {M.short_label(x) for x in M.nodes if M.file[x] == f}
        orphans, news = collections.defaultdict(list), collections.defaultdict(list)
        for lab, mod in e.items():
            if lab not in claimed: orphans[lab.split('#')[0]].append(mod)
        for n in ns: news[M.short_label(n).split('#')[0]].append(n)
        for name, xs in news.items():
            if len(xs) == 1 and len(orphans.get(name, ())) == 1 and asg[xs[0]] is None:
                asg[xs[0]] = orphans[name][0]; kept += 1
    for n in unmapped:
        if asg[n] is not None: continue
        e = files.get(M.file[n])
        m = collections.Counter(e.values()).most_common(1)[0][0] if isinstance(e, dict) else R.seed(M.file[n])[0]
        t = M.extended_node(n)
        if t is not None and m == R.default and asg.get(t): m = asg[t]
        asg[n] = m
    return asg, unmapped, kept


def load_map(path):
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)['files']


def write_map(path, files, rules_path):
    data = {'about': 'Generated by `modulemap.py assign --write` from rules.json and the index; review the diff. '
                     'A string is the module of the whole file; an object names the module of each declaration '
                     'of a split file: Name, or Name(ext)#first for an extension, where first is its first member '
                     '(else the protocols it conforms to), and #k the k-th of a label still shared.',
            'files': files}
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(data, fh, indent=1, sort_keys=True)
        fh.write('\n')


# ── output ────────────────────────────────────────────────────────────────────────────────────────────────
def annotation(msg):
    """A message as a GitHub workflow command's data: `%`, CR and LF escaped, or the annotation ends at the line."""
    return msg.replace('%', '%25').replace('\r', '%0D').replace('\n', '%0A')


def table(M, R, asg):
    rows = collections.defaultdict(lambda: [0, 0.0, set()])
    for n in M.nodes:
        r = rows[asg[n]]; r[0] += 1; r[1] += M.lines[n]; r[2].add(M.file[n])
    total = sum(r[1] for r in rows.values()) or 1
    out = [f'{"module":20s} {"decls":>6s} {"files":>6s} {"lines":>8s} {"%":>6s}']
    for m in R.order:
        if m in rows:
            r = rows[m]
            out.append(f'{m:20s} {r[0]:6d} {len(r[2]):6d} {r[1]:8.0f} {r[1] / total * 100:6.1f}')
    return '\n'.join(out)


# GitHub keeps 10 warning annotations per step (its documented limit, as the review of 5110dbc cited it; not
# measured here) and drops the rest without a word. Past that, the last one says how many more the log lists.
GITHUB_ANNOTATIONS = 10


def report(findings, R, github, verbose, level='warning'):
    """Print the findings by check; with `github`, a workflow annotation of `level` (`error` when the check gates,
    `warning` under `--exit-zero`) for each new one. Returns the new findings."""
    by = collections.defaultdict(list)
    for x in findings: by[x.check].append(x)
    new = [x for x in findings if x.new]
    room = len(new) if len(new) <= GITHUB_ANNOTATIONS else GITHUB_ANNOTATIONS - 1
    annotated = 0
    order = ['upward', 'owns-neither', 'witness', 'public-above', 'posix', 'umbrella', 'lower', 'rules']
    for c in order:
        xs = by.get(c, [])
        n_new = sum(1 for x in xs if x.new)
        sched = collections.Counter(x.scheduled for x in xs if x.scheduled)
        sites = collections.Counter()
        for x in xs:
            if x.scheduled: sites[x.scheduled] += x.weight
        acc = sum(1 for x in xs if x.accepted and not x.scheduled)      # each finding counted once, as tagged
        extra = []
        if sched: extra.append('scheduled ' + ', '.join(f'{k} {v} ({sites[k]} refs)' if sites[k] != v else f'{k} {v}'
                                                         for k, v in sorted(sched.items())))
        if acc: extra.append(f'accepted {acc}')
        print(f'{c:13s} {n_new:4d} new' + (f'   ({"; ".join(extra)})' if extra else ''))
        for x in xs:
            if x.new or verbose:
                tag = f'[{x.scheduled}] ' if x.scheduled else '[accepted] ' if x.accepted else ''
                loc = f'{R.source}/{x.file}:{x.line}: ' if x.file else ''
                print(f'    {tag}{loc}{x.message}')
            if x.new and github and annotated < room:
                where = f' file={R.source}/{x.file},line={x.line},' if x.file else ' '
                print(f'::{level}{where}title=ModuleMap {c}::{annotation(x.message)}')
                annotated += 1
    if github and annotated < len(new):
        print(f'::{level} title=ModuleMap::{len(new) - annotated} more new findings than GitHub shows as annotations: '
              f'this step\'s log lists all {len(new)}')
    return new


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('command', choices=['check', 'assign', 'explain'])
    ap.add_argument('pattern', nargs='?', help='explain: a regular expression over declaration labels')
    ap.add_argument('--store', help='the index store (default: the one a build wrote last, of '
                    '.build/*/debug/index/store and .build/out)')
    ap.add_argument('--lib', help='libIndexStore (default: beside the toolchain\'s swift)')
    ap.add_argument('--rules', default=RULES)
    ap.add_argument('--map', default=MAP)
    ap.add_argument('--fresh', action='store_true', help='check: run the assigner instead of reading map.json')
    ap.add_argument('--write', action='store_true', help='assign: rewrite map.json')
    ap.add_argument('--github', action='store_true', help='check: GitHub Actions annotations (errors; warnings with '
                    '--exit-zero)')
    ap.add_argument('--exit-zero', action='store_true', help='check: exit 0 even with new findings (warning only)')
    ap.add_argument('-v', '--verbose', action='store_true', help='list scheduled and accepted findings too')
    a = ap.parse_intermixed_args(argv)          # options before or after the pattern
    try:
        return run(a)
    except (Exception, SystemExit) as e:
        # A failure of the tool itself (no store, a libIndexStore that will not load, a bug in this tool) means nothing
        # was checked. A `check` reports it as one annotation at the check's own level. Under --exit-zero it is a
        # warning and status 0, because warning only means warning only. When the check gates, as CI's does, it is an
        # error and status 1, so the failed step says why. A gating run without --github re-raises, for the traceback.
        if not (a.command == 'check' and (a.exit_zero or a.github)): raise
        if isinstance(e, SystemExit):
            if e.code in (None, 0): raise
            msg = str(e)
        else:
            traceback.print_exc()
            msg = f'modulemap failed, so nothing was checked: {type(e).__name__}: {e}'
        level = 'warning' if a.exit_zero else 'error'
        print(f'::{level} title=ModuleMap::{annotation(msg)}' if a.github else msg)
        return 0 if a.exit_zero else 1


def run(a):
    t0 = time.time()
    R = Rules.load(a.rules)
    store = a.store or indexstore.find_store(ROOT)
    M = Model.load(ROOT, R.source, store, a.lib, modules=R.order if R.by_directory else None)
    t1 = time.time()
    print(f'modulemap: {len(M.files)} files, {len(M.nodes)} declarations, '
          f'{sum(len(v) for v in M.edges.values())} edges from {store} ({t1 - t0:.1f} s)')
    if M.stale:
        print(f'modulemap: WARNING: {len(M.stale)} sources are newer than the index (rebuild first): '
              f'{", ".join(M.stale[:5])}{" ..." if len(M.stale) > 5 else ""}')
    named = {x for ls in R.lower.values() for x in ls or ()}
    unknown = sorted(named - M.lower_visible)
    if unknown:
        raise SystemExit(f'rules.json: a lower list names {", ".join(unknown)}, which is not a module beside '
                         f'{R.source} that its sources import')
    # Every lower module the sources see must be in the index, not only the ones a list names: a list denies the
    # ones it leaves out (TUIkitFoundation leaves out TUIkitImage), and a module the index lacks would deny nothing.
    unread = sorted(M.lower_visible - M.lower_modules)
    if unread and any(ls is not None for ls in R.lower.values()):
        raise SystemExit(f'modulemap: the index has no definitions of {", ".join(unread)}, which {R.source} imports, '
                         f'so the `lower` lists cannot be checked: rebuild the whole package (a debug `swift build`)')
    if a.command == 'assign':
        asg, info = assigner.assign(M, R)
        print(f'assigner: {info} ({time.time() - t1:.1f} s)')
        print(table(M, R, asg))
        files = to_map(M, R, asg)
        if os.path.exists(a.map):
            old = load_map(a.map)
            prev = resolve(M, R, old)[0]
            moved = collections.Counter((prev[n], asg[n]) for n in M.nodes if prev[n] != asg[n])
            print(f'against {os.path.relpath(a.map, ROOT)}: {sum(moved.values())} declarations change module',
                  dict(moved.most_common(12)) if moved else '')
            if a.verbose:
                for n in M.nodes:
                    if prev[n] != asg[n]: print(f'    {M.label(n)}: {prev[n]} -> {asg[n]}')
        if a.write:
            write_map(a.map, files, a.rules)
            print(f'wrote {os.path.relpath(a.map, ROOT)}')
        return 0
    if a.fresh or not os.path.exists(a.map):
        asg, _ = assigner.assign(M, R)
        unmapped, kept = [], 0
    else:
        asg, unmapped, kept = resolve(M, R, load_map(a.map))
    if a.command == 'explain':
        rx = re.compile(a.pattern or '.')
        for n in M.nodes:
            if not rx.search(M.label(n)): continue
            seed = R.seed(M.file[n])
            print(f'{M.label(n)}  ->  {asg[n]}   (file rule: {seed[0]}{", pinned" if seed[1] else ""}; '
                  f'{"public" if n in M.public else "internal"}; {M.lines[n]:.0f} lines)')
            grp = getattr(assigner.assign, 'groups', {}).get(n, [n])
            if len(grp) > 1:
                others = ', '.join(M.label(x) for x in grp if x != n)
                print(f'    moves with {len(grp) - 1} other declaration(s): {others[:600]}')
            how = getattr(assigner.assign, 'last', {}).get(n)
            if how: print(f'    last moved by the assigner\'s {how!r} step')
            for b, (k, (f, ln)) in sorted(M.edges.get(n, {}).items(), key=lambda kv: -kv[1][0]):
                if asg[b] != asg[n]: print(f'    uses    {asg[b]:18s} {M.label(b)} ({k}, {f}:{ln})')
            for s in M.nodes:
                e = M.edges.get(s, {}).get(n)
                if e and asg[s] != asg[n]: print(f'    used by {asg[s]:18s} {M.label(s)} ({e[0]}, {e[1][0]}:{e[1][1]})')
        return 0
    if unmapped:
        files = sorted({M.file[n] for n in unmapped})
        print(f'modulemap: {len(unmapped)} declarations in {len(files)} files are not in map.json; placed by the '
              f'rules{f", {kept} kept an edited entry" if kept else ""} (refresh with `assign --write`)')
    findings = checks.run_all(M, R, asg, ROOT)
    new = report(findings, R, a.github, a.verbose, 'warning' if a.exit_zero else 'error')
    print(f'modulemap: {len(new)} new finding{"s" if len(new) != 1 else ""} '
          f'({len(findings) - len(new)} scheduled or accepted) in {time.time() - t0:.1f} s')
    return 1 if new and not a.exit_zero else 0


if __name__ == '__main__':
    sys.exit(main())
