import SwiftUI

@main
struct Probe {
    static func show(_ label: String, _ p: Path) {
        print(label, "=>", p.description)
        print("   bounds", p.boundingRect)
    }
    @MainActor static func main() {
        var p = Path()
        p.move(to: CGPoint(x: 0, y: 0)); p.addLine(to: CGPoint(x: 10, y: 0)); p.addLine(to: CGPoint(x: 10, y: 10)); p.closeSubpath()
        show("tri", p)
        print("   parsed", Path(p.description)?.description ?? "nil")
        print("   contains(5,2)", p.contains(CGPoint(x: 8, y: 2)), p.contains(CGPoint(x: 2, y: 8)))
        var a = Path(); a.addArc(center: .init(x: 10, y: 10), radius: 5, startAngle: .degrees(0), endAngle: .degrees(90), clockwise: false)
        show("arc ccw=false 0..90", a)
        var b = Path(); b.addArc(center: .init(x: 10, y: 10), radius: 5, startAngle: .degrees(0), endAngle: .degrees(90), clockwise: true)
        show("arc clockwise 0..90", b)
        var r = Path(); r.addRelativeArc(center: .init(x: 0, y: 0), radius: 1, startAngle: .zero, delta: .degrees(90))
        show("relarc 90", r)
        var t = Path(); t.move(to: .init(x: 0, y: 0)); t.addArc(tangent1End: .init(x: 10, y: 0), tangent2End: .init(x: 10, y: 10), radius: 3)
        show("tangent arc", t)
        show("rect", Path(CGRect(x: 1, y: 2, width: 3, height: 4)))
        show("ellipse", Path(ellipseIn: CGRect(x: 0, y: 0, width: 10, height: 20)))
        show("rrect circ", Path(roundedRect: CGRect(x: 0, y: 0, width: 20, height: 10), cornerRadius: 3, style: .circular))
        show("rrect cont", Path(roundedRect: CGRect(x: 0, y: 0, width: 20, height: 10), cornerRadius: 3, style: .continuous))
        show("rrect uneven", Path(roundedRect: CGRect(x: 0, y: 0, width: 20, height: 10), cornerRadii: .init(topLeading: 1, bottomLeading: 2, bottomTrailing: 3, topTrailing: 4), style: .circular))
        show("rrect big", Path(roundedRect: CGRect(x: 0, y: 0, width: 20, height: 10), cornerRadius: 30, style: .circular))
        show("Rectangle", Rectangle().path(in: CGRect(x: 0, y: 0, width: 4, height: 2)))
        show("Circle", Circle().path(in: CGRect(x: 0, y: 0, width: 20, height: 10)))
        show("Ellipse", Ellipse().path(in: CGRect(x: 0, y: 0, width: 20, height: 10)))
        show("Capsule", Capsule().path(in: CGRect(x: 0, y: 0, width: 20, height: 10)))
        show("Capsule cont", Capsule(style: .continuous).path(in: CGRect(x: 0, y: 0, width: 20, height: 10)))
        show("RoundedRectangle", RoundedRectangle(cornerRadius: 3).path(in: CGRect(x: 0, y: 0, width: 20, height: 10)))
        show("Uneven", UnevenRoundedRectangle(topLeadingRadius: 2, bottomTrailingRadius: 4).path(in: CGRect(x: 0, y: 0, width: 20, height: 10)))
        show("trim .25-.75 rect", Path(CGRect(x: 0, y: 0, width: 10, height: 10)).trimmedPath(from: 0.25, to: 0.75))
        show("trim .1-.3 circle", Circle().path(in: CGRect(x: 0, y: 0, width: 10, height: 10)).trimmedPath(from: 0.1, to: 0.3))
        show("trim .9-.1", Path(CGRect(x: 0, y: 0, width: 10, height: 10)).trimmedPath(from: 0.9, to: 0.1))
        show("Rect inset 2", Rectangle().inset(by: 2).path(in: CGRect(x: 0, y: 0, width: 10, height: 10)))
        show("Circle inset 2", Circle().inset(by: 2).path(in: CGRect(x: 0, y: 0, width: 10, height: 10)))
        show("RRect inset 2", RoundedRectangle(cornerRadius: 3).inset(by: 2).path(in: CGRect(x: 0, y: 0, width: 20, height: 10)))
        show("offset", Rectangle().offset(x: 2, y: 3).path(in: CGRect(x: 0, y: 0, width: 4, height: 2)))
        show("rotation 90", Rectangle().rotation(.degrees(90)).path(in: CGRect(x: 0, y: 0, width: 4, height: 2)))
        show("scale 2", Rectangle().scale(2).path(in: CGRect(x: 0, y: 0, width: 4, height: 2)))
        show("scale x2 topLeading", Rectangle().scale(x: 2, y: 1, anchor: .topLeading).path(in: CGRect(x: 0, y: 0, width: 4, height: 2)))
        show("size 2x2", Rectangle().size(width: 2, height: 2).path(in: CGRect(x: 10, y: 10, width: 4, height: 4)))
        show("size anchor center", Rectangle().size(CGSize(width: 2, height: 2), anchor: .center).path(in: CGRect(x: 10, y: 10, width: 4, height: 4)))
        show("trim shape", Rectangle().trim(from: 0, to: 0.5).path(in: CGRect(x: 0, y: 0, width: 4, height: 2)))
        show("stroke shape", Rectangle().stroke(lineWidth: 2).path(in: CGRect(x: 0, y: 0, width: 4, height: 2)))
        show("quad", Path { $0.move(to: .zero); $0.addQuadCurve(to: .init(x: 10, y: 0), control: .init(x: 5, y: 10)) })
        show("curve", Path { $0.move(to: .zero); $0.addCurve(to: .init(x: 10, y: 0), control1: .init(x: 0, y: 10), control2: .init(x: 10, y: 10)) })
        show("addLine no move", Path { $0.addLine(to: .init(x: 3, y: 4)) })
        show("addRects", Path { $0.addRects([CGRect(x: 0, y: 0, width: 1, height: 1), CGRect(x: 2, y: 2, width: 1, height: 1)]) })
        show("addLines", Path { $0.addLines([.zero, .init(x: 1, y: 1), .init(x: 2, y: 0)]) })
        print("currentPoint after close", Path { $0.move(to: .init(x: 1, y: 1)); $0.addLine(to: .init(x: 5, y: 1)); $0.closeSubpath() }.currentPoint as Any)
        print("empty bounds", Path().boundingRect, Path().isEmpty, Path { $0.move(to: .init(x: 3, y: 3)) }.isEmpty, Path { $0.move(to: .init(x: 3, y: 3)) }.boundingRect)
        print("parse fail", Path("1 2 x") as Any, Path("") as Any)
        print("eo contains", Path { $0.addRect(CGRect(x: 0, y: 0, width: 10, height: 10)); $0.addRect(CGRect(x: 2, y: 2, width: 6, height: 6)) }.contains(CGPoint(x: 5, y: 5), eoFill: true))
        print("applying", Path(CGRect(x: 0, y: 0, width: 1, height: 1)).applying(CGAffineTransform(scaleX: 2, y: 3)).description)
        print("offsetBy", Path(CGRect(x: 0, y: 0, width: 1, height: 1)).offsetBy(dx: 5, dy: 6).description)
        print("Rect cornerRadii eq", RectangleCornerRadii(topLeading: 1) == RectangleCornerRadii(topLeading: 1))
        print("StrokeStyle default", StrokeStyle())
        print("FillStyle default", FillStyle())
        print("roles", Rectangle.role, Circle.role, Path.role)
        print("anim RR", RoundedRectangle(cornerRadius: 3).animatableData)
        print("anim Rect", Rectangle().animatableData)
    }
}
