#!/usr/bin/env python3
"""Carry out plan.py's plan: move each test file into its target's directory, give it the narrowest import its
target allows, and write the new targets into Package.swift.

- `import TUI` (the umbrella) becomes the modules at the top of what the file itself needs: `import TUILists`
  in a Lists test, `import TUIApp` and `import TUILists` in one that also drives the App, `import
  TUIFoundation` in a base one. Integration keeps the umbrella. Each module re-exports what it depends on, so
  those are enough; an import of a module outside them is dropped, so it can't tie the target to that module.
- A file that uses a helper which moved to another support target gains `@testable import` of that target.
- Each target depends on what its files import (the umbrella only for Integration), and on the support targets
  its files use. Package.swift's generated block sits between two marker comments, so a re-run replaces it.

Run from the package root, after a debug build and analyze.py + plan.py. `--dry-run` prints what would move.

Usage: move.py PLAN.json ANALYSIS.json [--dry-run]
"""
import argparse, collections, glob, json, os, re, subprocess, sys

BEGIN = "        // ── TESTSPLIT: generated by Tools/TestSplit/move.py ──"
END = "        // ── end TESTSPLIT ──"
UMBRELLA_TARGETS = ["TUITests", "TUICollectionTests", "TUIControlTests", "TUIAppTests"]
SUPPORT = "TUITestSupport"


def source_path(key):
    target, name = key.split("/")
    found = glob.glob(f"Tests/{target}/**/{name}.swift", recursive=True)
    if len(found) != 1:
        print(f"skipped {key}: not one source file ({found}); re-run analyze.py on a fresh build", file=sys.stderr)
        return None
    return found[0]


def module_for(target):
    """The library module a test or support target is for, or None for Integration."""
    for suffix in ("TestSupport", "Tests"):
        if target.endswith(suffix):
            base = target[: -len(suffix)]
            break
    if base in ("TUIIntegration",):
        return None
    if target == SUPPORT:
        return "TUIFoundation"
    return base


IMPORT = r"(?m)^([ \t]*)(@testable )?import (\w+)"


def rewrite(text, modules, extra_support):
    """`text` with the umbrella import replaced by imports of `modules` (None keeps the umbrella), and an
    `@testable import` of each of `extra_support`. An import inside an `#if` keeps its indentation."""
    if modules is not None:
        present = imported_modules(text)
        umbrella = re.search(r"(?m)^([ \t]*)import TUI\n", text)
        missing = [m for m in sorted(modules) if m not in present]
        if umbrella:
            indent = umbrella.group(1)
            text = text[:umbrella.start()] + "".join(f"{indent}import {m}\n" for m in missing) + text[umbrella.end():]
        else:
            # No umbrella import to replace (a support file importing its modules one by one): add them.
            text = add_after_imports(text, [f"import {m}" for m in missing])
    return sort_import_runs(add_after_imports(text, [f"@testable import {s}" for s in sorted(extra_support)]))


def is_header(line):
    """A line of the file's header comment: a `//` comment, not a `///` doc comment, which is a declaration's."""
    return line.startswith("//") and not line.startswith("///")


def sort_import_runs(text):
    """Each run of consecutive import lines sorted by module, as SwiftLint's `sorted_imports` wants: an added
    import goes where it belongs, not last."""
    lines = text.split("\n")
    out, run = [], []
    pattern = re.compile(r"^[ \t]*(?:@testable )?import (\w+)")

    def flush():
        out.extend(sorted(run, key=lambda l: pattern.match(l).group(1).lower()))
        run.clear()

    for line in lines:
        if pattern.match(line):
            run.append(line)
        else:
            flush()
            out.append(line)
    flush()
    return "\n".join(out)


def add_after_imports(text, lines):
    for line in lines:
        if line.split()[-1] in imported_modules(text):
            continue
        imports = list(re.finditer(IMPORT + r".*$", text))
        if imports:
            # After the last import, at its indentation, so it sits with the others.
            at, indent = imports[-1].end(), imports[-1].group(1)
            text = text[:at] + "\n" + indent + line + text[at:]
        else:
            # After the header comment (and a support file's guard).
            lines_ = text.split("\n")
            at = 0
            while at < len(lines_) and (is_header(lines_[at]) or lines_[at].startswith("#if") or not lines_[at].strip()):
                at += 1
            lines_.insert(at, line + "\n")
            text = "\n".join(lines_)
    return text


def reexports():
    """{module: the modules an `import` of it brings in}, from each module's `@_exported import`s, to the end."""
    direct = collections.defaultdict(set)
    for path in glob.glob("Sources/*/**/*.swift", recursive=True):
        for exported in re.findall(r"(?m)^@_exported import (\w+)", open(path).read()):
            direct[path.split("/")[1]].add(exported)
    found = {}
    for module in list(direct):
        seen, stack = set(), [module]
        while stack:
            for dep in direct.get(stack.pop(), ()):
                if dep not in seen:
                    seen.add(dep)
                    stack.append(dep)
        found[module] = seen
    return found


def covering(tops, needs, exports):
    """`tops`, and each module of `needs` none of those brings in: what a file must import to see what it uses.
    Not every module re-exports what it depends on (TUIView doesn't TUICore)."""
    chosen = list(tops)
    seen = set()
    for module in chosen:
        seen |= {module} | exports.get(module, set())
    for module in sorted(needs):
        if module not in seen:
            chosen.append(module)
            seen |= {module} | exports.get(module, set())
    return chosen


def closure(graph, module):
    found, stack = set(), [module]
    while stack:
        for dep in graph.get(stack.pop(), []):
            if dep not in found:
                found.add(dep)
                stack.append(dep)
    return found


def prune(text, allowed):
    """Drops the imports of library modules a target is not to depend on. Many files `@testable import
    TUIApp` (or another module) and use nothing of it; kept, they would tie the target to it."""
    def keep(match):
        return match.group(0) if match.group(2) in allowed or not match.group(2).startswith("TUI") else ""
    return re.sub(r"(?m)^[ \t]*(@testable )?import (\w+)\n", keep, text)


GUARD = "#if TUIKIT_TEST_SUPPORT && canImport(Testing)"
GUARD_COMMENT = ("// Built for tests only: a plain `swift build -c release` compiles this file empty (see "
                 "TUITestSupport in Package.swift).")


def wrapped_for_support(text):
    """A file entering a support target is wrapped in its guard, after the header comment, as every support file
    is (`Tools/validate-test-boundaries.sh` fails one that is not)."""
    if GUARD in text:
        return text
    lines = text.split("\n")
    at = 0
    while at < len(lines) and (is_header(lines[at]) or not lines[at].strip()):
        at += 1
    body = "\n".join(lines[at:]).rstrip("\n")
    header = "\n".join(lines[:at]).rstrip("\n")
    return f"{header}\n\n{GUARD_COMMENT}\n{GUARD}\n\n{body}\n\n#endif\n"


def imported_modules(text):
    return {m.group(3) for m in re.finditer(IMPORT, text)}


def carry_fixtures(moves):
    """`__Fixtures__` (read by path, `#filePath`-relative) goes where the tests that read it went; returns the
    target that now holds it."""
    holder = None
    for src, dst, text in moves:
        if "__Fixtures__" in text:
            holder = dst.split("/")[1]
            old = os.path.join("Tests", src.split("/")[1], "__Fixtures__")
            new = os.path.join("Tests", holder, "__Fixtures__")
            if os.path.isdir(old) and old != new:
                subprocess.run(["git", "mv", old, new], check=True)
    return holder


def write_package(deps, fixtures_holder):
    """Replaces the umbrella suite's four test targets and its support target with the split's."""
    text = open("Package.swift").read()
    start = text.index("        // The umbrella suite: integration tests + every test that exercises")
    end_marker = """            swiftSettings: [.define("TUIKIT_TEST_SUPPORT", .when(configuration: .debug))]
        ),
"""
    end = text.index(end_marker, start) + len(end_marker)
    order = lambda t: (t.endswith("TestSupport") is False, t != SUPPORT, t)
    lines = [
        "        // The framework's suite, a test target per module (the owner's request B-TC1-1, 2026-10-12; placed",
        "        // by Tools/TestSplit from the compiler's index of what each file references). A test lives in the",
        "        // target of the highest module it needs, its helpers' needs counted, and its target depends on",
        '        // what its files import, so an edit to a module rebuilds only the tests that can see it:',
        '        // - TUIFoundationTests: tests needing only TUIFoundation and what it re-exports;',
        '        // - TUIAppTests: those needing TUIApp and no feature module;',
        '        // - TUI<Module>Tests: those needing one feature module, with or without TUIApp;',
        '        // - TUIIntegrationTests, the one target that depends on everything: those needing two.',
        '        // A test target is one module, whose interface is emitted by one serial job whatever the -j, and',
        '        // every edit to any of its files waits for that job: more, smaller targets also re-emit less',
        '        // and compile in parallel (the commit that split them records the times). Test files that share',
        '        // a helper declared in one of them land together. Tools/validate-test-boundaries.sh checks that',
        '        // every test file imports only what its target depends on.',
        '        //',
        '        // Helpers two targets share live in support targets split the same way: TUITestSupport for the',
        "        // base, TUIAppTestSupport, and a feature's own (TUIListsTestSupport, ...). Each is a plain",
        '        // target, as CTestSupport is, which `swift build` builds even without `--build-tests`: in a release',
        '        // build, which has no testability, its `@testable import`s of the library would fail ("module',
        '        // \'TUIFoundation\' was not compiled for testing"). So every file is wrapped in',
        '        // `#if TUIKIT_TEST_SUPPORT && canImport(Testing)`, which these targets define for debug builds',
        '        // only, and a release build compiles them empty. The alternatives, measured 2026-10-10 in a probe',
        '        // package (lane TT2) on Swift 6.2.4, 6.3.3 and 6.4.0: as a test target the others depend on,',
        "        // 6.4's build system still builds it in release; `swift build -c release --product <a library",
        '        // product>` builds every target on 6.2 and 6.3; and `package` access instead of `@testable` would',
        "        // put every internal a helper uses into the library's package interface. A release TEST build",
        '        // passes the define itself:',
        '        // `swift build -c release --build-tests -Xswiftc -enable-testing -Xswiftc -DTUIKIT_TEST_SUPPORT`.',
        '        // `canImport(Testing)`: a static Linux SDK ships no Testing module, and a debug build of the whole',
        '        // package for it would fail here. Golden snapshots are read and written by path (#filePath-relative,',
        '        // see TestHelpers/SnapshotTesting.swift), not via the resource bundle, so they are excluded from',
        '        // the build rather than declared as resources; so are the asset-catalogue fixtures.',
    ]
    def wrapped(names, indent):
        """`names` quoted, as lines of at most 120 columns at `indent`, each ending in a comma."""
        out, line = [], indent
        for name in names:
            item = f'"{name}",'
            if len(line) + len(item) + 1 > 120 and line.strip():
                out.append(line.rstrip())
                line = indent
            line += item + " "
        if line.strip():
            out.append(line.rstrip())
        return out

    for target in sorted(deps, key=order):
        support = target.endswith("TestSupport")
        names = sorted(deps[target])
        integration = target == "TUIIntegrationTests"
        if integration:
            # Everything, as the umbrella suite did, and the support targets its files use.
            names = [d for d in names if d.endswith("TestSupport") and d != "CTestSupport"]
        lines += [f"        .{'target' if support else 'testTarget'}(", f'            name: "{target}",']
        lines += [f"            dependencies: {'umbrellaTestDependencies + ' if integration else ''}["]
        lines += wrapped(names, "                ")
        tail = "            ]"
        if support:
            exclude = ', exclude: ["__Snapshots__"]' if target == SUPPORT else ""
            lines += [tail + ",", f'            path: "Tests/{target}"{exclude},',
                      '            swiftSettings: [.define("TUIKIT_TEST_SUPPORT", .when(configuration: .debug))]']
        elif target == fixtures_holder:
            lines += [tail + ",", '            exclude: ["__Fixtures__"]']
        else:
            lines += [tail]
        lines += ["        ),"]
    open("Package.swift", "w").write(text[:start] + "\n".join(lines) + "\n" + text[end:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("plan")
    ap.add_argument("analysis")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    loaded = json.load(open(args.plan))
    plan, tops = loaded["plan"], loaded["tops"]
    analysis = json.load(open(args.analysis))
    files, graph = analysis["files"], analysis["graph"]
    deps = collections.defaultdict(set)
    exports = reexports()
    moves = []
    for key, target in sorted(plan.items()):
        src = source_path(key)
        if src is None:
            continue
        old_target = key.split("/")[0]
        # Keep any subdirectory under the target (SharedFixtures/, Mocks/, ...).
        rel = os.path.relpath(src, f"Tests/{old_target}")
        dst = os.path.join("Tests", target, rel)
        support_used = {plan[h] for h in files[key]["helpers"] if plan[h].endswith("TestSupport")} - {target}
        # A test file already imports TUITestSupport; a helper that left it for another support target did
        # not need to, being inside it, and now must.
        original = open(src).read()
        if target.endswith("TestSupport") and target != SUPPORT and old_target == SUPPORT:
            support_used = support_used | {SUPPORT}
        module = module_for(target)
        if module is None:
            text = rewrite(original, None, support_used - {SUPPORT} if target.endswith("Tests") else support_used)
        else:
            own = covering([m for m in tops[key] if m != "TUIIntegration"] or [module],
                           set(files[key]["modules"]), exports)
            text = rewrite(original, own, support_used - {SUPPORT} if target.endswith("Tests") else support_used)
            allowed = set(own) | {SUPPORT, "TUIWidthCorpus"} | support_used
            for m in own:
                allowed |= closure(graph, m)
            if target.endswith("TestSupport"):
                allowed -= {target}
            text = prune(text, allowed)
        if target.endswith("TestSupport"):
            text = wrapped_for_support(text)
        deps[target] |= (imported_modules(text) - {target}) | support_used
        moves.append((src, dst, text))
    for target in deps:
        module = module_for(target)
        if module:
            deps[target].add(module)
        if target.endswith("Tests") and target != SUPPORT:
            deps[target].add(SUPPORT)
    # Only the package's own targets: an import of a system module (Foundation, ObjectiveC, Symbols, ...) is
    # not a dependency.
    known = set(graph) | set(deps) | {"CTestSupport", "TUIWidthCorpus"}
    for target in deps:
        deps[target] &= known
    if args.dry_run:
        for target in sorted(deps):
            count = sum(1 for _, dst, _ in moves if dst.split("/")[1] == target)
            print(f"{count:5}  {target}: {', '.join(sorted(deps[target]))}")
        return
    for src, dst, text in moves:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if src != dst:
            subprocess.run(["git", "mv", src, dst], check=True)
        open(dst, "w").write(text)
    json.dump({t: sorted(d) for t, d in deps.items()}, open(".build/test-split-deps.json", "w"), indent=1)
    json.dump({dst: src for src, dst, _ in moves}, open(".build/test-split-moves.json", "w"), indent=1)
    fixtures = carry_fixtures(moves)
    write_package(deps, fixtures)
    print(f"moved {sum(1 for s, d, _ in moves if s != d)} files; dependencies in .build/test-split-deps.json")


if __name__ == "__main__":
    sys.exit(main())
